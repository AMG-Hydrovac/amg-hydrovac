// Embeds the site's rate-sheet code and the Anton font into the serverless function bundle,
// so the emailed PDF is built by exactly the same code as the on-screen one.
// Runs at Netlify build time (see netlify.toml) and can be run locally: node netlify/embed.js
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const quoteSrc = fs.readFileSync(path.join(root, "assets", "js", "quote.js"), "utf8");
const fontB64 = fs.readFileSync(path.join(root, "assets", "fonts", "anton-regular.ttf")).toString("base64");
const out = "// GENERATED by netlify/embed.js — do not edit by hand.\n" +
  "module.exports = { QUOTE_SRC: " + JSON.stringify(quoteSrc) + ", ANTON_B64: " + JSON.stringify(fontB64) + " };\n";
const dest = path.join(__dirname, "functions", "lib", "embedded.js");
fs.writeFileSync(dest, out);
console.log("embedded.js written: quote.js " + quoteSrc.length + " chars, font " + fontB64.length + " b64 chars");
